
"use client";

import { Suspense } from 'react';
import { useRouter, useSearchParams } from "next/navigation";
import { GameGeneratorForm } from "../game-generator-form"; // Adjusted path
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { ArrowLeft, Lightbulb } from "lucide-react";
import Link from "next/link";

const moods = ["Fun", "Deep", "Spiritual", "Icebreaker", "Challenge", "Trivia"] as const;
type MoodEnum = typeof moods[number];

function GroupGameGeneratorContent() {
  const router = useRouter();
  const searchParams = useSearchParams();
  const initialMoodQuery = searchParams.get("mood") as MoodEnum | null;

  // Validate if the mood from query is one of the allowed moods
  const validInitialMood = initialMoodQuery && moods.includes(initialMoodQuery) ? initialMoodQuery : undefined;

  const handleMoodChange = (newMood: MoodEnum) => {
    // Optionally update URL as mood changes in the form on this page
    router.replace(`/games/group-game-generator?mood=${newMood}`, { scroll: false });
  };

  return (
    <div className="space-y-6">
      <Card className="shadow-lg">
        <CardHeader>
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-3">
                <Lightbulb className="h-7 w-7 text-primary" />
                <CardTitle className="text-2xl">AI Generated Group Game</CardTitle>
            </div>
            <Button variant="outline" asChild>
              <Link href="/games">
                <ArrowLeft className="mr-2 h-4 w-4" />
                Back to Games
              </Link>
            </Button>
          </div>
          <CardDescription>
            Here's a game idea generated by AI based on your selected mood. You can also generate new ideas below.
          </CardDescription>
        </CardHeader>
        <CardContent>
          <GameGeneratorForm 
            initialMood={validInitialMood} 
            onMoodChange={handleMoodChange} 
          />
        </CardContent>
      </Card>
    </div>
  );
}

export default function GroupGameGeneratorPage() {
  // Suspense is necessary because useSearchParams() can suspend during initial render.
  return (
    <Suspense fallback={<div className="flex justify-center items-center h-64">Loading game generator...</div>}>
      <GroupGameGeneratorContent />
    </Suspense>
  );
}

    